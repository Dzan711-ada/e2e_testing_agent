"""Snippet checks and deterministic export of a standalone pytest test."""

import ast
import json
from pathlib import Path
import textwrap


FORBIDDEN_NODES = (
    ast.Import, ast.ImportFrom, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef,
    ast.While, ast.For, ast.AsyncFor, ast.Try, ast.With, ast.AsyncWith,
    ast.Return, ast.Raise, ast.Global, ast.Nonlocal, ast.Delete, ast.Lambda,
)
FORBIDDEN_CALLS = {"exec", "eval", "compile", "open", "__import__", "getattr", "setattr", "input", "breakpoint"}


def validate_snippet(source: str, *, assertion: bool = False) -> str:
    source = source.strip()
    if source.startswith("```") and source.endswith("```"):
        source = "\n".join(source.splitlines()[1:-1]).strip()
    if not source or len(source) > 20000:
        raise ValueError("生成代码为空或过长。")
    tree = ast.parse(source)
    if not tree.body:
        raise ValueError("代码片段没有可执行语句。")
    for node in ast.walk(tree):
        if isinstance(node, FORBIDDEN_NODES):
            raise ValueError(f"代码片段不支持 {type(node).__name__}，只生成当前步骤的直接操作。")
        if isinstance(node, ast.Attribute) and node.attr.startswith("_"):
            raise ValueError("代码片段不能访问内部属性。")
        if isinstance(node, ast.Name) and node.id.startswith("__"):
            raise ValueError("代码片段不能使用内部名称。")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in FORBIDDEN_CALLS:
            raise ValueError(f"代码片段不能调用 {node.func.id}。")
        if isinstance(node, ast.Assert) and isinstance(node.test, ast.Constant):
            raise ValueError("断言必须检查实际结果，不能检查常量。")
    uses_page = any(isinstance(n, ast.Name) and n.id == "page" for n in ast.walk(tree))
    if not uses_page:
        raise ValueError("代码片段没有引用 page。")
    has_assertion = any(
        isinstance(n, ast.Assert) or (
            isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "expect"
        ) for n in ast.walk(tree)
    )
    if assertion and not has_assertion:
        raise ValueError("结果检查步骤必须包含 expect 或 assert。")
    # Compile in an async function to reject invalid await/break/continue syntax.
    compile("async def _validated():\n" + textwrap.indent(source, "    "), "<generated-step>", "exec")
    return source


def render_test(*, target_url: str, snippets: list[str], headless: bool,
                action_timeout_ms: int, browsers_path: Path) -> str:
    """Export only validated actions; replay needs Python, pytest and Playwright."""
    body = "\n\n".join(snippets)
    encoded_url = repr(target_url)
    encoded_browsers = repr(str(browsers_path))
    return (
        '# Generated by E2E Testing Agent. Run with: python -m pytest this_file.py -q\n'
        'import asyncio\nimport os\nfrom pathlib import Path\nimport re\n\n'
        f'os.environ.setdefault("PLAYWRIGHT_BROWSERS_PATH", {encoded_browsers})\n'
        'from playwright.async_api import async_playwright, expect\n\n\n'
        'async def run_scenario():\n'
        '    artifact_dir = Path(__file__).resolve().parent\n'
        '    async with async_playwright() as playwright:\n'
        f'        browser = await playwright.chromium.launch(channel="chromium", headless={headless!r})\n'
        '        context = await browser.new_context()\n'
        '        await context.tracing.start(screenshots=True, snapshots=True, sources=True)\n'
        '        page = await context.new_page()\n'
        f'        page.set_default_timeout({action_timeout_ms})\n'
        f'        page.set_default_navigation_timeout({action_timeout_ms})\n'
        '        try:\n'
        f'            await page.goto({encoded_url}, wait_until="domcontentloaded")\n'
        + textwrap.indent(body, '            ') + '\n'
        '        finally:\n'
        '            try:\n'
        '                await page.screenshot(path=str(artifact_dir / "replay.png"), full_page=True, timeout=5000)\n'
        '            except Exception:\n'
        '                pass\n'
        '            try:\n'
        '                await context.tracing.stop(path=str(artifact_dir / "replay-trace.zip"))\n'
        '            except Exception:\n'
        '                pass\n'
        '            await browser.close()\n\n\n'
        'def test_generated_scenario():\n'
        '    asyncio.run(run_scenario())\n'
    )


def save_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
